LANGS = ("en", "ar", "bg", "ca", "cs", "da", "de", "el", "es", "et", "fa", "fi", "fr", "fy", "gl", "he", "hr", "hu", "id", "is", "it", "ku", "lt", "lv", "mk", "nb", "nl", "nn", "pl", "pt", "pt_br", "ro", "ru", "sk", "sl", "sq", "sr", "sv", "th", "tr", "uk", "vi", "zh_cn", "zh_hk")

# config.osd.language (dupa curatare) -> cod de modul
_ALIAS = {"hk": "zh_hk", "hk_hk": "zh_hk", "nb_no": "nb", "nn_no": "nn", "no": "nb", "pt_br": "pt_br", "zh": "zh_cn", "zh_cn": "zh_cn", "zh_hk": "zh_hk", "zh_mo": "zh_hk", "zh_sg": "zh_cn", "zh_tw": "zh_hk"}
_CU_TARA = ("pt_br", "zh_cn", "zh_hk")
_LITERE = "abcdefghijklmnopqrstuvwxyz_"


def cod_limba(raw):
	"""Valoarea din config.osd.language -> cod din LANGS ("en" daca nu il stim). Nu arunca."""
	try:
		s = str(raw).strip().replace("-", "_").lower()
		s = "".join([c for c in s if c in _LITERE])[:12]
	except Exception:
		return "en"
	if s in _ALIAS:
		return _ALIAS[s]
	if s in _CU_TARA:
		return s
	b = s.split("_")[0]
	b = _ALIAS.get(b, b)
	if b in LANGS:
		return b
	return "en"


def incarca(cod):
	"""Tabelul unei limbi (dict cheie -> text). {} pentru engleza sau la orice eroare.

	Modulul se scoate din sys.modules dupa citire: in memorie ramane doar tabelul
	limbii active, iar la schimbarea limbii cel vechi se elibereaza.
	"""
	if cod == "en" or cod not in LANGS:
		return {}
	rez = {}
	for nume in ("Components.Converter.HdsLang_" + cod, "HdsLang_" + cod):
		try:
			mod = __import__(nume, globals(), {}, ["T"], 0)
		except Exception:
			continue
		try:
			t = getattr(mod, "T", None)
			if isinstance(t, dict):
				rez = t
		finally:
			try:
				sys.modules.pop(nume, None)
				parinte = sys.modules.get(nume.rpartition(".")[0])
				if parinte is not None and hasattr(parinte, "HdsLang_" + cod):
					delattr(parinte, "HdsLang_" + cod)
			except Exception:
				pass
		break
	return rez
