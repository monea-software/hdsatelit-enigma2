import tokenize
import sys


def filter(g):
	# PEP 479: StopIteration nu are voie sa iasa dintr-un generator, deci se opreste explicit
	try:
		while True:
			t = next(g)
			if t[1] == "/*":
				while next(g)[1] != "*/":
					pass
				continue
			if t[1] == "//":
				while next(g)[1] != "\n":
					pass
				continue

			if t[1] != "\n":
				yield t[1]
	except (StopIteration, tokenize.TokenError):
		return


def do_file(f, mode):
	with open(f, 'r') as fp:
		tokens = filter(tokenize.generate_tokens(fp.readline))

		sys.stderr.write("parsing %s\n" % f)

		state = 0
		classstate = 0
		classname = None
		firsthit = 1

		while True:
			try:
				t = next(tokens)
			except StopIteration:
				break

			if t == "class":
				classname = next(tokens)
				classstate = state

			if t == "{":
				state = state + 1

			if t == "}":
				state = state - 1

			if t == "enum" and state == classstate + 1:
				actionname = next(tokens)

				if actionname == "{":
					while next(tokens) != "}":
						pass
					continue

				if actionname[-7:] == "Actions":
					if next(tokens) != "{":
						sys.stderr.write("%s %s\n" % (classname, actionname))
						raise Exception("action enum must be simple.")

					counter = 0

					while True:
						t = next(tokens)

						if t == "=":
							next(tokens)
							t = next(tokens)

						if t == "}":
							break

						if counter:
							if t != ",":
								raise Exception("no comma")
							t = next(tokens)

						if firsthit:
							if mode == "include":
								# hack hack hack!!
								print("#include <lib/" + '/'.join(f.split('/')[-2:]) + ">")
							else:
								print("\t// " + f)
							firsthit = 0

						if mode == "parse":
							print("{\"" + actionname + "\", \"" + t + "\", " + "::".join((classname, t)) + "},")

						counter = counter + 1


mode = sys.argv[1]

if mode == "parse":
	print("""
	/* generated by parseactions.py - do not modify! */
struct eActionList
{
	const char *m_context, *m_action;
	int m_id;
} actions[]={""")

for x in sys.argv[2:]:
	do_file(x, mode)

if mode == "parse":
	print("};")
